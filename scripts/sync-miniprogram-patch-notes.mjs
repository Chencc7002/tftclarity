import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { getCurrentPatchNote } from "../src/app/small-window-ui/patch-notes.js";

const patch = getCurrentPatchNote("zh-CN");
const labels = { buff: "增强", nerf: "削弱", mixed: "调整" };
const result = {
  ...patch,
  history: patch.history.map(({ groups, ...revision }) => ({
    ...revision,
    kind: { release: "正式版本", balance: "平衡调整", hotfix: "热补丁" }[revision.kind],
    changes: groups.flatMap((group) => group.changes.map(({ body, ...change }) => ({
      ...change,
      label: body,
      text: `${labels[change.direction]}｜${body}：${change.before} → ${change.after}`
    })))
  }))
};
const file = new URL("../miniprogram/data/patch-notes.js", import.meta.url);
const content = `// Generated by node scripts/sync-miniprogram-patch-notes.mjs\nmodule.exports = ${JSON.stringify(result, null, 2)};\n`;
if (process.argv.includes("--check")) {
  assert.equal(readFileSync(file, "utf8"), content, "Mini program patch notes are out of sync");
} else {
  writeFileSync(file, content);
}
console.log(`Mini program patch notes ${process.argv.includes("--check") ? "verified" : "updated"}: ${patch.version}`);
